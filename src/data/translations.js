// Flatten all paired topics
export const ALL_PAIRED_TOPICS = [
  ...CATEGORY_TOPICS.cybersecurity,
  ...CATEGORY_TOPICS.ai,
  ...CATEGORY_TOPICS.self_learning,
];

export const DEFAULT_TOPICS_EN = ALL_PAIRED_TOPICS.map((t) => t.en);
export const DEFAULT_TOPICS_AR = ALL_PAIRED_TOPICS.map((t) => t.ar);

export function getLocalizedTopic(topic, targetLang) {
  if (!topic) return '';
  const match = ALL_PAIRED_TOPICS.find(
    (t) => t.en.trim() === topic.trim() || t.ar.trim() === topic.trim()
  );
  if (match) {
    return targetLang === 'ar' ? match.ar : match.en;
  }
  return topic;
}

